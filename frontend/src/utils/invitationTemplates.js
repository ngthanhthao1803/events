export function getTemplateById(id) {
  if (!id) return INVITATION_TEMPLATES[0];
  const found = INVITATION_TEMPLATES.find((t) => t.id === id || t.alias === id);
  return found || INVITATION_TEMPLATES[0];
}

export function detectSuggestedTemplate(title = "", description = "") {
  const text = `${title} ${description}`.toLowerCase();
  for (const t of INVITATION_TEMPLATES) {
    if (t.keywords.some((k) => text.includes(k))) {
      return t.id;
    }
  }
  return "classic-gold";
}
